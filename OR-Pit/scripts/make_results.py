"""Collect evaluation JSONs from runs/ into results/RESULTS.md and results/results.json.

    python scripts/make_results.py
Rows are included only for runs/eval files that exist; every number comes from a real
evaluation file (paths are listed in the output).
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from orpit.config import resolve  # noqa: E402

RUNS = resolve("runs")
ABLATIONS = [
    ("A", "abl_A_v1", "v1 model (original spec), new training recipe"),
    ("B", "abl_B_frontend_mask", "A + masks on frontend features (R2.3)"),
    ("C", "abl_C_gate_halting", "B + gated cgMLP (R2.2) + halting-aware matching (R2.5)"),
    ("D", "abl_D_v2", "C + FiLM-TCN mask refinement (R2.4) = OR-PiT v2"),
]
FINALS = [
    ("OR-PiT v1 (6.1 h, original recipe)", "gtx1650_budget"),
    ("OR-PiT v2 (final)", "final_orpit_v2"),
    ("Conv-TasNet (2-spk specialist, same budget)", "final_convtasnet"),
]
BENCH = [
    ("Libri2Mix noisy", "eval_libri2mix_noisy"),
    ("Libri2Mix clean", "eval_libri2mix_clean"),
    ("Libri3Mix noisy", "eval_libri3mix_noisy"),
]


def load(p):
    return json.load(open(p)) if p.exists() else None


def f(x, nd=2):
    return "–" if x is None else f"{x:.{nd}f}"


def pct(x):
    return "–" if x is None else f"{100 * x:.1f} %"


def tau(e):
    return "" if not e or e.get("threshold") is None else f" (τ={e['threshold']:.2f})"


def main():
    out, md, used = {}, [], []
    md.append(
        "# OR-PiT results\n\nAll numbers are SI-SDRi in dB (oracle Hungarian matching over all output slots)"
        " unless noted; *est-count* scores only the slots the halting head keeps. Generated by "
        "`scripts/make_results.py` from the evaluation files listed at the end.\n"
    )
    md.append("## Ablation (own test set: 1,000 test-clean mixtures, 2–5 speakers, WHAM! noise, 4 s)\n")
    md.append(
        "| | Variant | Overall | 2 spk | 3 spk | 4 spk | 5 spk | Count acc. (τ=0.5) | Count acc. (val-cal. τ) | Est-count SI-SDRi (cal.) |"
    )
    md.append("|---|---|---|---|---|---|---|---|---|---|")
    for tag, run, desc in ABLATIONS:
        p = RUNS / run / "eval_test.json"
        e = load(p)
        if not e:
            continue
        used.append(p)
        o = e["overall"]
        out[f"ablation_{tag}"] = e
        c = load(RUNS / run / "eval_test_cal.json")
        if c:
            used.append(RUNS / run / "eval_test_cal.json")
            out[f"ablation_{tag}_cal"] = c
        co = (c or {}).get("overall", {})
        md.append(
            f"| {tag} | {desc} | {f(o['si_sdri'])} | "
            + " | ".join(f(e.get(f"{n}spk", {}).get("si_sdri")) for n in (2, 3, 4, 5))
            + f" | {pct(o.get('count_acc'))} | {pct(co.get('count_acc'))}{tau(c)} | {f(co.get('si_sdri_estcount'))} |"
        )
    md.append("\n## Final models\n")
    md.append(
        "| Model | Params | Own test (2–5 spk) | 2 spk | Count acc. (τ=0.5) | Count acc. (val-cal. τ) | "
        "Est-count SI-SDRi (cal.) | " + " | ".join(b for b, _ in BENCH) + " | RTF 8 s (GTX 1650) |"
    )
    md.append("|---|---|---|---|---|---|---|" + "---|" * len(BENCH) + "---|")
    for name, run in FINALS:
        e, c, sp = (load(RUNS / run / x) for x in ("eval_test.json", "eval_test_cal.json", "speed.json"))
        for x, v in (
            ("eval_test.json", e),
            ("eval_test_cal.json", c),
            ("speed.json", sp),
            ("threshold.json", load(RUNS / run / "threshold.json")),
        ):
            if v:
                used.append(RUNS / run / x)
        bench = []
        for _, stem in BENCH:
            b = load(RUNS / run / f"{stem}.json")
            if b:
                used.append(RUNS / run / f"{stem}.json")
            bench.append(f(b["overall"]["si_sdri"]) if b else "–")
        if not e and all(x == "–" for x in bench):
            continue
        o, co = (e or {}).get("overall", {}), (c or {}).get("overall", {})
        out[run] = {
            "own_test": e,
            "own_test_cal": c,
            "speed": sp,
            **{stem: load(RUNS / run / f"{stem}.json") for _, stem in BENCH},
        }
        rtf = next((r.get("rtf") for r in (sp or {}).get("results", []) if r.get("seconds") == 8.0), None)
        params = f"{sp['params'] / 1e6:.2f} M" if sp else "–"
        md.append(
            f"| {name} | {params} | {f(o.get('si_sdri'))} | {f((e or {}).get('2spk', {}).get('si_sdri'))} | "
            f"{pct(o.get('count_acc'))} | {pct(co.get('count_acc'))}{tau(c)} | {f(co.get('si_sdri_estcount'))} | "
            + " | ".join(bench)
            + f" | {f(rtf, 3)} |"
        )
    md.append(
        "\nτ = halting threshold. *val-cal.* = the threshold that maximises count accuracy on the"
        " validation set (dev-clean), then applied unchanged to test. LibriMix columns use the"
        " calibrated threshold for counting but report oracle-matched SI-SDRi. Fairness note: oracle"
        " matching lets OR-PiT pick the best N of its 6 slots, while Conv-TasNet has exactly N outputs;"
        " the est-count column removes that advantage (only slots the halting head keeps are scored,"
        " missed speakers count as 0 dB).\n"
    )
    md.append("\n## LibriMix test sets: raw input vs. input normalised to −19 dBFS\n")
    md.append(
        "LibriMix mixtures are ~5 dB quieter than the training mixtures (median −24.8 vs −19.7 dBFS for"
        " 2 speakers, `scripts/level_stats.py`). *norm* rescales each input mixture to −19 dBFS"
        " before the model (SI-SDR is scale-invariant, so references are untouched).\n"
    )
    md.append(
        "| Model | Test set | SI-SDRi raw | SI-SDRi norm | Count acc. raw | Count acc. norm | Est-count raw | Est-count norm |"
    )
    md.append("|---|---|---|---|---|---|---|---|")
    for name, run in FINALS:
        for label, stem in BENCH:
            r, n = load(RUNS / run / f"{stem}.json"), load(RUNS / run / f"{stem}_norm.json")
            if not (r or n):
                continue
            if n:
                used.append(RUNS / run / f"{stem}_norm.json")
                out.setdefault(run, {})[f"{stem}_norm"] = n
            ro, no = (r or {}).get("overall", {}), (n or {}).get("overall", {})
            md.append(
                f"| {name} | {label} | {f(ro.get('si_sdri'))} | {f(no.get('si_sdri'))} | {pct(ro.get('count_acc'))} | "
                f"{pct(no.get('count_acc'))} | {f(ro.get('si_sdri_estcount'))} | {f(no.get('si_sdri_estcount'))} |"
            )
    md.append(
        "\nReference (different budget): LibriMix paper, Conv-TasNet trained on train-360, Libri2Mix noisy"
        " 16 kHz max mode: 13.5 dB; Libri3Mix noisy: 10.9 dB (Cosentino et al., 2020, Table 4).\n"
    )
    md.append("## Source files\n")
    md += [f"- `{p.relative_to(RUNS.parent).as_posix()}`" for p in used]
    dest = resolve("results")
    dest.mkdir(exist_ok=True)
    (dest / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    json.dump(out, open(dest / "results.json", "w"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
